"""Write RULES.md from the engine's rule registry and the seeded source-specific rules.

The general rules come from the RULES array in engine/funding-engine.js; the per-source parameters come from
data/seed.json. Run after editing either:  python -P tools/rules_doc.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
js = open(os.path.join(ROOT, 'engine', 'funding-engine.js'), encoding='utf-8').read()
block = js[js.index('const RULES = ['):js.index('const RULE = ')]
FIELD = r"(\w+): '((?:[^'\\]|\\.)*)'"
rules = []
for entry in re.findall(r'\{ id: .*? \},?\n', block):
    d = {k: v.replace("\\'", "'") for k, v in re.findall(FIELD, entry)}
    rules.append(d)

WHERE = {'COST': 'serviceCost, ownCost', 'REV': 'lineAmount, projectedAmount, ftaOperating', 'ELIG': 'checkUse', 'PREF': 'checkUse',
         'FED': 'evaluate (checks), buildLP (constraints)', 'MATCH': 'evaluate, buildLP', 'ALLOC': 'allocateFixed, draftShares, evaluate',
         'SVC': 'evaluate', 'OPT': 'buildLP, simplex, certify, explainUnused', 'RES': 'evaluate', 'SENS': 'sensitivity'}
GROUPS = [('COST', 'Costs'), ('REV', 'Revenue'), ('ELIG', 'Eligibility: required rules'), ('PREF', 'Eligibility: preferences'),
          ('FED', 'Federal share'), ('MATCH', 'Local match'), ('ALLOC', 'Fixed-share allocation'), ('SVC', 'Service checks'),
          ('OPT', 'Rules-based allocation (optimizer)'), ('RES', 'Results'), ('SENS', 'Sensitivity')]
KIND = {'calc': 'Calculation', 'required': 'Required rule', 'preference': 'Preference', 'check': 'Check', 'optimizer': 'Optimizer', 'result': 'Result'}
SEV = {'error': 'Error', 'warning': 'Warning', 'info': 'Info'}

T = json.load(open(os.path.join(ROOT, 'data', 'seed.json'), encoding='utf-8'))['tables']
prog = {p['program_id']: p for p in T['funding_program']}
svc = {s['service_id']: s['short_name'] for s in T['service']}
jur = {j['jurisdiction_id']: j['name'] for j in T['jurisdiction']}
ag = {a['agency_id']: a['short_name'] for a in T['agency']}
rules_by = {}
for r in T['eligibility_rule']:
    rules_by.setdefault(r['line_id'], {}).setdefault(r['strength'], {}).setdefault(r['rule_type'], []).append(r['value'])
cite = {}
for c in T['citation']:
    if c['entity_type'] == 'funding_line' and c['field'] in ('match', 'restrictions'):
        cite.setdefault(c['entity_id'], []).append(c['locator'])


def describe(group):
    out = []
    for t, vals in group.items():
        if t == 'service':
            out.append('services: ' + ', '.join(svc.get(v, v) for v in vals))
        elif t == 'agency':
            out.append('agency: ' + ', '.join(ag.get(v, v) for v in vals))
        elif t == 'jurisdiction_share':
            out.append('share of ' + ', '.join(jur.get(v, v) for v in vals))
        elif t == 'state':
            out.append('state: ' + ' or '.join(vals))
        elif t == 'area_class':
            out.append(' or '.join(vals) + ' service')
        else:
            out.append(t.replace('_', ' ') + ': ' + ', '.join(vals))
    return '; '.join(out)


def esc(s):
    return (s or '').replace('|', '\\|').replace('\n', ' ')


lines = ['# Rules applied by the funding model', '',
         'Generated by `tools/rules_doc.py` from the rule registry in `engine/funding-engine.js` and the source data in `data/seed.json`. '
         'Each rule ID appears in the code where the rule is applied and in every check result that cites it.', '',
         'Severity applies to rules that are checked against an allocation: an **error** breaks a required rule, cap, or match requirement; '
         'a **warning** flags a use outside a source\'s stated intent; **info** reports a gap or an unallocated amount.', '']
for prefix, title in GROUPS:
    grp = [r for r in rules if r['id'].startswith(prefix + '-')]
    if not grp:
        continue
    lines += [f'## {title}', '', f'Code: `{WHERE[prefix]}`', '', '| ID | Rule | Type | What the model does | Source |', '| --- | --- | --- | --- | --- |']
    for r in grp:
        kind = KIND.get(r.get('kind'), r.get('kind', '')) + (f" ({SEV[r['severity']]})" if r.get('severity') else '')
        lines.append(f"| {r['id']} | {esc(r['title'])} | {kind} | {esc(r['text'])} | {esc(r.get('source'))} |")
    lines.append('')

lines += ['## Source-specific rules', '',
          'The parameters each funding source supplies to the rules above. Required rules make a use ineligible (ELIG); preferred rules raise warnings (PREF). '
          'Federal share caps feed FED-02 and MATCH-01; "counts as match" feeds MATCH-02. Every source also carries PREF-04 (receiving agency).', '',
          '| Source | Agency | Level | Required (ELIG) | Preferred (PREF) | Federal share cap | Match | Where the rule comes from |', '| --- | --- | --- | --- | --- | --- | --- | --- |']
for l in sorted(T['funding_line'], key=lambda x: (x['recipient_agency_id'], x['line_id'])):
    r = rules_by.get(l['line_id'], {})
    level = prog[l['program_id']]['level']
    cap = '' if l['federal_share_cap'] is None else f"{l['federal_share_cap'] * 100:g}%" + (f" (ADA {l['federal_share_cap_ada'] * 100:g}%)" if l['federal_share_cap_ada'] is not None else '')
    match = 'match only (credit)' if l['match_only'] else ('needs match' if level == 'federal' else ('counts as match' if l['counts_as_match'] else 'does not count'))
    status = '' if l['status'] == 'budgeted' else f" ({l['status']})"
    lines.append(f"| {esc(l['name'])}{status} | {ag[l['recipient_agency_id']]} | {level} | {esc(describe(r.get('required', {}))) or '—'} | {esc(describe(r.get('preferred', {}))) or '—'} | {cap or '—'} | {match} | {esc('; '.join(cite.get(l['line_id'], [])))} |")
lines.append('')

with open(os.path.join(ROOT, 'RULES.md'), 'w', encoding='utf-8') as fh:
    fh.write('\n'.join(lines))
print(f'RULES.md: {len(rules)} general rules, {len(T["funding_line"])} sources')
